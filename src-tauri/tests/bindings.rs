//! AC-3: the generated TypeScript bindings are deterministic and match the committed file.
#![forbid(unsafe_code)]

use std::path::PathBuf;

const HEADER: &str = "// @generated by tauri-specta — do not edit";

fn committed_bindings_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("src")
        .join("contracts")
        .join("bindings.ts")
}

fn normalize(text: &str) -> String {
    text.strip_prefix('\u{feff}')
        .unwrap_or(text)
        .replace("\r\n", "\n")
}

fn render() -> String {
    match inkspark_lib::bindings_ts() {
        Ok(text) => text,
        Err(err) => panic!("bindings_ts() returned Err: {err}"),
    }
}

#[test]
fn bindings_ts_is_ok() {
    assert!(inkspark_lib::bindings_ts().is_ok());
}

#[test]
fn bindings_ts_contains_app_info_command_and_type() {
    let ts = render();
    assert!(ts.contains("appInfo"), "missing the appInfo command");
    assert!(
        ts.contains("export type AppInfo"),
        "missing `export type AppInfo`"
    );
}

#[test]
fn bindings_ts_starts_with_generated_header() {
    let ts = normalize(&render());
    assert!(
        ts.starts_with(HEADER),
        "bindings must start with `{HEADER}`, got: {:?}",
        ts.lines().next()
    );
}

#[test]
fn bindings_ts_is_deterministic() {
    let first = render();
    let second = render();
    assert!(
        first.as_bytes() == second.as_bytes(),
        "two calls to bindings_ts() produced different output"
    );
}

#[test]
fn bindings_ts_matches_committed_file() {
    let path = committed_bindings_path();
    let committed = match std::fs::read_to_string(&path) {
        Ok(text) => normalize(&text),
        Err(err) => panic!(
            "could not read {}: {err}. Run `npm run bindings`.",
            path.display()
        ),
    };
    let generated = normalize(&render());
    if generated != committed {
        let first_diff = generated
            .lines()
            .zip(committed.lines())
            .position(|(g, c)| g != c)
            .map_or_else(
                || "files differ in length".to_owned(),
                |i| format!("first difference at line {}", i + 1),
            );
        panic!("src/contracts/bindings.ts is out of date ({first_diff}). Run `npm run bindings`.");
    }
}
