//! InkSpark's Tauri backend.
#![forbid(unsafe_code)]

pub mod commands;
pub mod error;
pub mod project;
pub mod storage;

use std::path::PathBuf;
use std::sync::atomic::{AtomicU64, Ordering};

pub use commands::{AppInfo, OsKind, app_info};
pub use error::AppError;
pub use project::PageSummary;

/// The first line of the generated bindings file (M0 §3.3).
pub const BINDINGS_HEADER: &str = "// @generated by tauri-specta — do not edit";

/// The tauri-specta builder holding every command and exported type.
#[must_use]
pub fn specta_builder() -> tauri_specta::Builder<tauri::Wry> {
    tauri_specta::Builder::<tauri::Wry>::new()
        .commands(tauri_specta::collect_commands![
            commands::app_info,
            commands::open_project,
            commands::create_page,
            commands::read_page,
            commands::save_page
        ])
        .typ::<AppError>()
}

/// Renders the TypeScript bindings for [`specta_builder`] as text.
///
/// The output is deterministic, uses LF line endings and starts with [`BINDINGS_HEADER`].
///
/// # Errors
///
/// Returns a message when specta fails to export a type, or when the scratch file used by the
/// exporter cannot be read back.
pub fn bindings_ts() -> Result<String, String> {
    // tauri-specta only exports to a path, so render into a unique scratch file and read it back.
    // This is a build-tool scratch file, never a user file.
    let scratch = scratch_path();
    let exported = specta_builder()
        .export(
            specta_typescript::Typescript::default().header(BINDINGS_HEADER),
            &scratch,
        )
        .map_err(|err| format!("tauri-specta export failed: {err}"));
    let text = exported.and_then(|()| {
        std::fs::read_to_string(&scratch)
            .map_err(|err| format!("could not read {}: {err}", scratch.display()))
    });
    // Best-effort cleanup; a leftover file in the temp dir is harmless.
    let _ = std::fs::remove_file(&scratch);
    text.map(|t| t.replace("\r\n", "\n"))
}

fn scratch_path() -> PathBuf {
    static COUNTER: AtomicU64 = AtomicU64::new(0);
    let n = COUNTER.fetch_add(1, Ordering::Relaxed);
    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |d| d.as_nanos());
    std::env::temp_dir().join(format!(
        "inkspark-bindings-{}-{nanos}-{n}.ts",
        std::process::id()
    ))
}

/// Starts the app. Used by `main.rs`.
pub fn run() {
    let builder = specta_builder();
    let result = tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .invoke_handler(builder.invoke_handler())
        .run(tauri::generate_context!());
    if let Err(err) = result {
        eprintln!("InkSpark could not start: {err}");
        std::process::exit(1);
    }
}
