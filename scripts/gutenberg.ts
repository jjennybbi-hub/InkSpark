// Shared helpers for the excerpt scripts. Run with Node (it strips TypeScript types itself).
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

export interface Excerpt {
  text: string;
  author: string;
  work: string;
  year: number;
  gutenbergId: number;
  link: string;
  kind: "opening" | "passage";
}

const CACHE = ".gutenberg-cache";

/** Downloads a book's plain text once and keeps it in the git-ignored cache folder. */
export async function bookText(id: number): Promise<string> {
  mkdirSync(CACHE, { recursive: true });
  const file = `${CACHE}/${String(id)}.txt`;
  if (!existsSync(file)) {
    const res = await fetch(
      `https://www.gutenberg.org/cache/epub/${String(id)}/pg${String(id)}.txt`,
    );
    if (!res.ok) {
      throw new Error(`HTTP ${String(res.status)} for book ${String(id)}`);
    }
    writeFileSync(file, await res.text());
    await new Promise((r) => setTimeout(r, 700));
  }
  return readFileSync(file, "utf8");
}

/** Collapses every run of whitespace (line breaks included) and unifies byte-order marks. */
export function norm(s: string): string {
  return s.replace(/﻿/g, "").replace(/\s+/g, " ").trim();
}

export function bodyOf(raw: string): string {
  const text = raw.replace(/\r\n/g, "\n");
  const start = text.search(/\*\*\* ?START OF (THE|THIS) PROJECT GUTENBERG[^\n]*\n/);
  const end = text.search(/\*\*\* ?END OF (THE|THIS) PROJECT GUTENBERG/);
  const from = start < 0 ? 0 : text.indexOf("\n", start) + 1;
  return text.slice(from, end < 0 ? undefined : end);
}

export function titleOf(raw: string): string {
  return /^Title:\s*(.+)$/m.exec(raw)?.[1] ?? "";
}

export function excerptsFile(list: readonly Excerpt[]): string {
  const rows = list.map((e) => `  ${JSON.stringify(e)},`).join("\n");
  return `// Generated by scripts/build-excerpts.ts and pruned by scripts/verify-excerpts.ts. Do not edit by hand.
// Every text is copied by machine from Project Gutenberg (public domain).
export interface Excerpt {
  readonly text: string;
  readonly author: string;
  readonly work: string;
  readonly year: number;
  readonly gutenbergId: number;
  readonly link: string;
  readonly kind: "opening" | "passage";
}

export const EXCERPTS: readonly Excerpt[] = [
${rows}
];
`;
}
